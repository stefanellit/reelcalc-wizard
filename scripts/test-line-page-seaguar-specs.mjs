import assert from "node:assert/strict";
import fs from "node:fs";
import { normalizeSeaguar } from "./line-page-seaguar-specs.mjs";
const root = new URL("../", import.meta.url);
const read = name => JSON.parse(fs.readFileSync(new URL(name, root), "utf8"));
const reviews = read("research/line-pages/source-review.json");
const source = id => read(`research/line-pages/sources/${id}.json`);
const rows = id => normalizeSeaguar(source(id), reviews[id]);
assert.throws(() => rows("seaguar-basix"), /not passed/);
assert.equal(rows("seaguar-tatsu")[0].dia_in, .006);
assert.deepEqual(rows("seaguar-tatsu")[0].spool_sizes_yd,[200]);
assert.equal(rows("seaguar-abrazx").length,9);
assert.equal(rows("seaguar-red-label").find(r=>r.lb===6).dia_in,.007);
assert.deepEqual(rows("seaguar-red-label").find(r=>r.lb===4).spool_sizes_yd,[200]);
assert.deepEqual(rows("seaguar-red-label").find(r=>r.lb===20).spool_sizes_yd,[175,1000]);
assert.deepEqual(rows("seaguar-brawlr").find(r=>r.lb===30).spool_sizes_yd,[250]);
assert.equal(rows("seaguar-brawlr").length,11);
assert.deepEqual(rows("seaguar-jdm-r18-mainline")[0].spool_sizes_yd,[109]);
assert.deepEqual(rows("seaguar-jdm-pex8-micro-braid").map(r=>r.lb),[12,16,18,21,24,33]);
assert.equal(rows("seaguar-jdm-pex8-micro-braid")[0].spool_length_m,200);
const broken=source("seaguar-tatsu");
broken.variants[1].options[0]="4LB .009 in. /.205 mm dia.";
assert.throws(()=>normalizeSeaguar(broken,reviews[broken.id]),/conflicting diameter/);
const missing=source("seaguar-jdm-r18-mainline"); missing.description="";
assert.throws(()=>normalizeSeaguar(missing,reviews[missing.id]),/not supported/);
console.log("Passed 14 Seaguar source parsing and conflict-gate checks.");
